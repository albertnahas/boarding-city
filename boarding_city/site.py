"""Render a city into site/<key>/ and keep site/repos.json and the repo list in site/index.html in sync."""
import json, shutil
from . import config, inject_fog, inject_nav, inject_search

TEXTURES = ["d0.jpg", "d1.jpg", "d2.jpg", "d3.jpg"]


def render(data, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp = out_dir / ".base.html"
    fog = out_dir / ".fog.html"
    # "</" is escaped so code snippets in the data can never close the page's <script>
    blob = json.dumps(data, separators=(",", ":")).replace("</", "<\\/")
    tmp.write_text((config.ASSETS / "template.html").read_text().replace("__DATA__", blob))
    inject_fog.main(str(tmp), str(fog))
    inject_nav.main(str(fog), str(out_dir / "demo.html"))
    inject_search.main(str(out_dir / "demo.html"), str(out_dir / "demo.html"))
    tmp.unlink()
    fog.unlink()
    for t in TEXTURES:
        shutil.copy(config.ASSETS / t, out_dir / t)


def register(meta, site=config.SITE):
    p = site / "repos.json"
    repos = [r for r in (json.loads(p.read_text()) if p.exists() else []) if r["key"] != meta["key"]] + [meta]
    p.write_text(json.dumps(repos, indent=1))
    write_index(site)


def write_index(site=config.SITE):
    repos = json.loads((site / "repos.json").read_text())
    p = site / "index.html"
    h = p.read_text()
    a = h.index("const REPOS=[")
    b = h.index("];", a) + 2
    rows = ",\n  ".join(f'{{key:"{m["key"]}",repo:"{m["repo"]}",sha:"{m["sha"]}",src:"{m["key"]}/demo.html",files:{m["files"]},flows:{m["flows"]},cost:"${m["cost"]:.2f}"}}' for m in repos)
    p.write_text(h[:a] + "const REPOS=[  // generated by `python -m boarding_city site` from site/repos.json\n  " + rows + "];" + h[b:])
    print(f"{p}: {len(repos)} repos listed")
